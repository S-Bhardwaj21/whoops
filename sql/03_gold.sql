CREATE OR REPLACE SECURE VIEW COLD_CHAIN_COMPLIANCE.GOLD.VW_LOGISTICS_COMPLIANCE AS
SELECT
    SHIPMENT_ID,
    ORDER_ID,
    BATCH_ID,
    CUSTOMER_ID,
    COMPLIANCE_STATUS,
    ERP_STATUS,
    MINUTES_ABOVE_THRESHOLD,
    METRIC_DEFINITION_VERSION,
    DECISION_REASON
FROM COLD_CHAIN_COMPLIANCE.GOLD.GOLD_COMPLIANCE_FACTS;

CREATE OR REPLACE SECURE VIEW COLD_CHAIN_COMPLIANCE.GOLD.VW_QUALITY_SENSOR_EVIDENCE AS
SELECT
    EVENT_TS,
    TEMPERATURE_C,
    SENSOR_ID,
    SENSOR_STATUS,
    SHIPMENT_ID
FROM COLD_CHAIN_COMPLIANCE.BRONZE.IOT_TEMP_LOGS;
