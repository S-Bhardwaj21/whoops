    BREACH_ID VARCHAR(16777216),
    SHIPMENT_ID VARCHAR(16777216),
    SENSOR_ID VARCHAR(16777216),
    EVENT_ID VARCHAR(16777216),
    EVENT_TS TIMESTAMP_NTZ(9),
