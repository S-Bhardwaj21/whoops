CREATE OR REPLACE TABLE COLD_CHAIN_COMPLIANCE.GOLD.GOLD_COMPLIANCE_FACTS (
    SHIPMENT_ID VARCHAR(16777216),
    ORDER_ID VARCHAR(16777216),
    BATCH_ID VARCHAR(16777216),
    SUPPLIER_LOT_ID VARCHAR(16777216),
    CUSTOMER_ID VARCHAR(16777216),
    ERP_STATUS VARCHAR(16777216),
    MAX_TEMPERATURE_C NUMBER(5,2),
    ALLOWED_MAX_TEMPERATURE_C NUMBER(5,2),
    MINUTES_ABOVE_THRESHOLD NUMBER(38,0),
    ALLOWED_EXCURSION_MINUTES NUMBER(38,0),
    COMPLIANCE_STATUS VARCHAR(16777216),
    METRIC_DEFINITION VARCHAR(16777216),
    METRIC_DEFINITION_VERSION VARCHAR(16777216),
    DECISION_REASON VARCHAR(16777216),
    DECIDED_AT TIMESTAMP_NTZ(9) DEFAULT CURRENT_TIMESTAMP()
);

